"""
PDF Generation Service for TripWise.
Generates comprehensive, multi-page, publication-grade travel itinerary and budget reports
using ReportLab with dynamic pagination and professional branding.
"""

from __future__ import annotations
import io
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Table, TableStyle, Spacer, PageBreak, KeepTogether, HRFlowable
)
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute total page count
    and render running headers and footers on all pages.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running header on page 2+
        if self._pageNumber > 1:
            self.drawString(36, 806, "TripWise — Comprehensive Travel Itinerary & Budget Plan")
            self.drawRightString(559, 806, datetime.now().strftime("%d %b %Y"))
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(36, 800, 559, 800)

        # Running footer on all pages
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(36, 36, 559, 36)
        self.drawString(36, 24, "Generated by TripWise AI Travel Planning System · Verified Calculations & Real Tourist Points")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(559, 24, page_str)
        self.restoreState()


def generate_trip_pdf(trip_data: dict) -> bytes:
    """
    Generates a complete, multi-page trip report PDF from trip_data.
    Returns raw PDF bytes.
    """
    buffer = io.BytesIO()

    # Page setup: A4 with 36pt (0.5 inch) margins
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=36,
        rightMargin=36,
        topMargin=46,
        bottomMargin=46
    )

    usable_width = A4[0] - 72  # 523.27 pt

    styles = getSampleStyleSheet()

    # Custom typography styles
    brand_blue = colors.HexColor("#2563EB")
    brand_dark = colors.HexColor("#0F172A")
    brand_slate = colors.HexColor("#334155")
    brand_muted = colors.HexColor("#64748B")
    border_color = colors.HexColor("#E2E8F0")

    style_title = ParagraphStyle(
        "PDFTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.white
    )
    style_subtitle = ParagraphStyle(
        "PDFSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#DBEAFE")
    )
    style_h1 = ParagraphStyle(
        "PDFH1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=brand_dark,
        spaceBefore=12,
        spaceAfter=6
    )
    style_h2 = ParagraphStyle(
        "PDFH2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=14,
        textColor=brand_blue,
        spaceBefore=8,
        spaceAfter=4
    )
    style_body = ParagraphStyle(
        "PDFBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11.5,
        textColor=brand_slate
    )
    style_body_bold = ParagraphStyle(
        "PDFBodyBold",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11.5,
        textColor=brand_dark
    )
    style_body_muted = ParagraphStyle(
        "PDFBodyMuted",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=7.5,
        leading=10,
        textColor=brand_muted
    )
    style_cell = ParagraphStyle(
        "PDFCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=10.5,
        textColor=brand_slate
    )
    style_cell_bold = ParagraphStyle(
        "PDFCellBold",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10.5,
        textColor=brand_dark
    )
    style_cell_header = ParagraphStyle(
        "PDFCellHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10.5,
        textColor=colors.white
    )

    elements = []

    # ─── 1. BRAND HEADER BANNER ───
    dest = trip_data.get("destination", "Your Destination")
    start_loc = trip_data.get("start_location", "Home City")
    start_date = trip_data.get("start_date", "")
    end_date = trip_data.get("end_date", "")
    num_days = trip_data.get("num_days", len(trip_data.get("itinerary", [])))
    num_nights = trip_data.get("num_nights", max(0, num_days - 1))
    travelers = trip_data.get("travelers", 2)
    currency = trip_data.get("currency", "INR")

    header_table_data = [
        [
            Paragraph("✈ TripWise Travel Itinerary", style_title),
            Paragraph(f"Generated: {datetime.now().strftime('%d %b %Y')}", ParagraphStyle("RightDate", parent=style_subtitle, alignment=2))
        ],
        [
            Paragraph(f"Comprehensive Itinerary & Budget Plan for <b>{dest}</b> from <b>{start_loc}</b>", style_subtitle),
            Paragraph("Official Travel Document", ParagraphStyle("RightSub", parent=style_subtitle, alignment=2))
        ]
    ]
    header_table = Table(header_table_data, colWidths=[usable_width * 0.7, usable_width * 0.3])
    header_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), brand_blue),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    elements.append(header_table)
    elements.append(Spacer(1, 10))

    # ─── 2. TRIP OVERVIEW BOX ───
    overview_data = [
        [
            Paragraph("<b>Destination:</b>", style_cell),
            Paragraph(str(dest), style_cell_bold),
            Paragraph("<b>Dates:</b>", style_cell),
            Paragraph(f"{start_date} to {end_date}", style_cell_bold)
        ],
        [
            Paragraph("<b>Starting From:</b>", style_cell),
            Paragraph(str(start_loc), style_cell_bold),
            Paragraph("<b>Duration:</b>", style_cell),
            Paragraph(f"{num_days} Days / {num_nights} Nights", style_cell_bold)
        ],
        [
            Paragraph("<b>Travellers:</b>", style_cell),
            Paragraph(f"{travelers} Person(s)", style_cell_bold),
            Paragraph("<b>Currency:</b>", style_cell),
            Paragraph(str(currency), style_cell_bold)
        ]
    ]
    intercity = trip_data.get("intercity_travel", {})
    if intercity.get("distance_km"):
        overview_data.append([
            Paragraph("<b>Transit Distance:</b>", style_cell),
            Paragraph(f"{intercity.get('distance_km')} km ({intercity.get('estimated_duration', 'N/A')})", style_cell_bold),
            Paragraph("<b>Route Provider:</b>", style_cell),
            Paragraph(str(intercity.get("provider", "OSRM Road Router")), style_cell)
        ])

    overview_table = Table(overview_data, colWidths=[usable_width * 0.22, usable_width * 0.28, usable_width * 0.22, usable_width * 0.28])
    overview_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 1, border_color),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, border_color),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    elements.append(overview_table)
    elements.append(Spacer(1, 10))

    # ─── 3. BUDGET SUMMARY & EXPENSE BREAKDOWN ───
    ba = trip_data.get("budget_analysis", {})
    if ba:
        elements.append(Paragraph("💰 Budget & Financial Cost Analysis", style_h1))

        est_cost = ba.get("total_estimated_trip_cost", 0)
        avail_budget = ba.get("available_budget_total", 0)
        status = ba.get("budget_status", "sufficient")
        diff = ba.get("budget_difference", 0)

        status_color = colors.HexColor("#16A34A") if status == "sufficient" else colors.HexColor("#DC2626")
        status_label = "✅ SUFFICIENT BUDGET" if status == "sufficient" else "⚠️ BUDGET SHORTFALL DETECTED"

        budget_summary_rows = [
            [
                Paragraph("<b>Total Estimated Cost:</b>", style_cell),
                Paragraph(f"<b>{currency} {est_cost:,.0f}</b>", style_cell_bold),
                Paragraph("<b>Available Budget:</b>", style_cell),
                Paragraph(f"{currency} {avail_budget:,.0f}", style_cell_bold)
            ],
            [
                Paragraph("<b>Budget Status:</b>", style_cell),
                Paragraph(f"<font color='{status_color.hexval()}'><b>{status_label}</b></font>", style_cell),
                Paragraph("<b>Balance / Difference:</b>", style_cell),
                Paragraph(f"<b>{currency} {diff:+,.0f}</b>", style_cell_bold)
            ]
        ]
        b_summary_table = Table(budget_summary_rows, colWidths=[usable_width * 0.25, usable_width * 0.25, usable_width * 0.25, usable_width * 0.25])
        b_summary_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EFF6FF")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#BFDBFE")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#DBEAFE")),
            ("PADDING", (0, 0), (-1, -1), 5),
        ]))
        elements.append(b_summary_table)
        elements.append(Spacer(1, 6))

        # Expense Breakdown Table
        cats = ba.get("categories", {})
        breakdown_data = [
            [
                Paragraph("Expense Category", style_cell_header),
                Paragraph(f"Total ({currency})", style_cell_header),
                Paragraph(f"Per Person ({currency})", style_cell_header),
                Paragraph("% of Total", style_cell_header)
            ]
        ]
        cat_labels = [
            ("transportation", "🚗 Intercity & Local Transportation"),
            ("accommodation", "🏨 Accommodation & Lodging"),
            ("food", "🍲 Food & Daily Dining"),
            ("sightseeing", "🎟️ Sightseeing & Attraction Tickets"),
            ("miscellaneous", "🛡️ Miscellaneous & Contingency")
        ]
        for key, label in cat_labels:
            c_info = cats.get(key, {})
            tot = c_info.get("total", 0)
            pp = c_info.get("per_person", 0)
            pct = (tot / est_cost * 100) if est_cost > 0 else 0
            breakdown_data.append([
                Paragraph(label, style_cell),
                Paragraph(f"{currency} {tot:,.0f}", style_cell_bold),
                Paragraph(f"{currency} {pp:,.0f}", style_cell),
                Paragraph(f"{pct:.1f}%", style_cell)
            ])

        # Mathematical total row verifying 100% reconciliation
        pp_cost = ba.get("total_estimated_per_person", est_cost / travelers if travelers else est_cost)
        breakdown_data.append([
            Paragraph("<b>TOTAL ESTIMATED TRIP COST</b>", style_cell_bold),
            Paragraph(f"<b>{currency} {est_cost:,.0f}</b>", style_cell_bold),
            Paragraph(f"<b>{currency} {pp_cost:,.0f}</b>", style_cell_bold),
            Paragraph("<b>100.0%</b>", style_cell_bold)
        ])

        b_table = Table(breakdown_data, colWidths=[usable_width * 0.44, usable_width * 0.20, usable_width * 0.20, usable_width * 0.16])
        b_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), brand_dark),
            ("ROWBACKGROUNDS", (0, 1), (-1, -2), [colors.white, colors.HexColor("#F8FAFC")]),
            ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#E2E8F0")),
            ("LINEABOVE", (0, -1), (-1, -1), 1, brand_dark),
            ("GRID", (0, 0), (-1, -1), 0.5, border_color),
            ("PADDING", (0, 0), (-1, -1), 4),
        ]))
        elements.append(b_table)
        elements.append(Spacer(1, 6))

        # Suggestions if budget shortfall
        if ba.get("suggestions") and status == "insufficient":
            sugg_text = "<br/>".join([f"• {s}" for s in ba["suggestions"]])
            elements.append(Paragraph(f"<b>Optimization Recommendations:</b><br/>{sugg_text}", style_body_muted))
            elements.append(Spacer(1, 6))

    # ─── 4. TRANSPORTATION COMPARISON TABLE ───
    trans_comp = trip_data.get("transportation_comparison", {})
    options = trans_comp.get("options", [])
    if options:
        elements.append(Paragraph("🚆 Transportation Options Comparison (5 Modes)", style_h1))
        trans_rows = [
            [
                Paragraph("Mode", style_cell_header),
                Paragraph(f"One-Way ({currency})", style_cell_header),
                Paragraph(f"Round Trip ({currency})", style_cell_header),
                Paragraph("Travel Duration", style_cell_header),
                Paragraph("Highlights / Badges", style_cell_header)
            ]
        ]
        for opt in options:
            badges = ", ".join(opt.get("badges", []))
            avail = opt.get("available", True)

            if not avail:
                one_way_cell = Paragraph("<font color='#94A3B8'>Route N/A</font>", style_cell)
                return_cell = Paragraph("<font color='#94A3B8'>Route N/A</font>", style_cell)
                dur_cell = Paragraph("<font color='#94A3B8'>N/A</font>", style_cell)
                notes_text = opt.get("details", "Distance not practical for scheduled air routes.")
            else:
                one_way_val = opt.get("one_way_total") or opt.get("one_way_total_inr") or 0
                return_val = opt.get("return_total") or opt.get("return_total_inr") or opt.get("total_cost") or 0
                pp_val = opt.get("cost_per_person") or opt.get("cost_per_person_inr") or opt.get("fare_per_person_inr") or 0
                ret_pp = opt.get("return_cost_per_person") or round(return_val / travelers) if travelers else return_val

                one_way_str = f"{currency} {one_way_val:,.0f}"
                if travelers > 1 and pp_val > 0:
                    one_way_str += f"<br/><font color='#64748B'>({currency} {pp_val:,.0f}/pax)</font>"
                return_str = f"{currency} {return_val:,.0f}"
                if travelers > 1 and ret_pp > 0:
                    return_str += f"<br/><font color='#64748B'>({currency} {ret_pp:,.0f}/pax)</font>"

                one_way_cell = Paragraph(one_way_str, style_cell)
                return_cell = Paragraph(return_str, style_cell_bold)
                duration_str = opt.get("duration_formatted") or opt.get("duration", "N/A")
                dur_cell = Paragraph(str(duration_str), style_cell)
                notes_text = badges or opt.get("notes", "Standard")
                if opt.get("is_budget_basis"):
                    notes_text = f"<b>★ Selected in Budget</b> · {notes_text}"

            trans_rows.append([
                Paragraph(f"<b>{opt.get('mode')}</b>", style_cell_bold),
                one_way_cell,
                return_cell,
                dur_cell,
                Paragraph(notes_text, style_cell)
            ])

        trans_table = Table(trans_rows, colWidths=[usable_width * 0.20, usable_width * 0.20, usable_width * 0.18, usable_width * 0.18, usable_width * 0.24])
        trans_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E293B")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ("GRID", (0, 0), (-1, -1), 0.5, border_color),
            ("PADDING", (0, 0), (-1, -1), 4),
        ]))
        elements.append(trans_table)

        # Reconciliation note connecting transportation options to the budget breakdown
        trans_cat = ba.get("categories", {}).get("transportation", {})
        trans_tot = trans_cat.get("total", 0)
        selected_mode = trans_cat.get("selected_mode", "Selected Mode")
        elements.append(Spacer(1, 3))
        elements.append(Paragraph(
            f"ℹ️ <b>Transportation Budget Reconciliation:</b> Total transportation in the budget breakdown above is "
            f"<b>{currency} {trans_tot:,.0f}</b>. This directly adopts the selected <b>{selected_mode}</b> round-trip option "
            f"for {travelers} traveller(s) (One-way: {currency} {trans_cat.get('intercity_outbound', 0):,.0f}, "
            f"Round-trip: {currency} {trans_tot:,.0f}) with exact mathematical reconciliation.",
            style_body_muted
        ))
        elements.append(Spacer(1, 8))

    # ─── 5. WEATHER SUMMARY (IF AVAILABLE) ───
    weather = trip_data.get("weather", {})
    if weather and weather.get("available"):
        elements.append(Paragraph("🌤 Destination Weather & Climate Advice", style_h1))
        wind_spd = weather.get("wind_speed_kmh", weather.get("wind_speed", 10))
        weather_text = (
            f"<b>Temperature:</b> {weather.get('temperature')}°C | "
            f"<b>Condition:</b> {weather.get('condition')} | "
            f"<b>Humidity:</b> {weather.get('humidity')}% | "
            f"<b>Wind Speed:</b> {wind_spd} km/h"
        )
        elements.append(Paragraph(weather_text, style_body))

        if weather.get("forecast_note"):
            elements.append(Paragraph(f"ℹ️ <i>{weather['forecast_note']}</i>", style_body_muted))

        if weather.get("travel_advice"):
            advice_str = " • ".join(weather["travel_advice"])
            elements.append(Paragraph(f"<b>Packing & Climate Advice:</b> {advice_str}", style_body_muted))
        elements.append(Spacer(1, 8))

    # PageBreak before day-by-day itinerary to guarantee clean presentation
    elements.append(PageBreak())

    # ─── 6. DAY-BY-DAY ITINERARY (EVERY SINGLE DAY) ───
    elements.append(Paragraph(f"📅 Day-by-Day Detailed Itinerary ({num_days} Days)", style_h1))

    itinerary_days = trip_data.get("itinerary", [])
    for d in itinerary_days:
        d_num = d.get("day_number", 1)
        d_date = d.get("date_formatted", d.get("date", f"Day {d_num}"))
        is_rest = d.get("is_rest_day", False)
        rest_note = d.get("rest_day_note", "")
        route_km = d.get("day_total_route_km", 0)

        # Day Header
        day_header_title = f"Day {d_num} — {d_date}"
        if is_rest:
            day_header_title += " [Leisure & Exploration Day]"
        else:
            route_m_to_a = d.get("route_morning_to_afternoon", {})
            route_a_to_e = d.get("route_afternoon_to_evening", {})
            modes = [route_m_to_a.get("mode"), route_a_to_e.get("mode")]
            if "ferry" in modes:
                day_header_title += f" (~{route_km} km Marine Ferry Travel)"
            elif "boat" in modes:
                day_header_title += f" (~{route_km} km Marine Boat Travel)"
            else:
                day_header_title += f" (~{route_km} km Road Travel)"

        day_elements = []
        day_elements.append(Paragraph(day_header_title, style_h2))

        if is_rest and rest_note:
            rest_table = Table([[Paragraph(f"ℹ️ <b>Rest & Free Day:</b> {rest_note}", style_body_muted)]], colWidths=[usable_width])
            rest_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F0FDF4")),
                ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#BBF7D0")),
                ("PADDING", (0, 0), (-1, -1), 6),
            ]))
            day_elements.append(rest_table)
            day_elements.append(Spacer(1, 4))

        # Activities Table for this day: Morning, Afternoon, Evening (Dynamic Duration-Matched Schedules)
        m_slot = d.get("morning")
        a_slot = d.get("afternoon")
        e_slot = d.get("evening")
        m_time = m_slot.get("time", "09:00 – 11:30") if m_slot else "09:00 – 11:30"
        a_time = a_slot.get("time", "13:00 – 15:30") if a_slot else "13:00 – 15:30"
        e_time = e_slot.get("time", "17:00 – 19:30") if e_slot else "17:00 – 19:30"

        slots = [
            (f"🌅 Morning<br/><font color='#64748B'>{m_time}</font>", m_slot),
            (f"☀️ Afternoon<br/><font color='#64748B'>{a_time}</font>", a_slot),
            (f"🌆 Evening<br/><font color='#64748B'>{e_time}</font>", e_slot)
        ]

        day_rows = [
            [
                Paragraph("Time / Period", style_cell_header),
                Paragraph("Attraction & Details", style_cell_header),
                Paragraph("Duration & Hours", style_cell_header),
                Paragraph(f"Ticket ({currency})", style_cell_header)
            ]
        ]

        for period_label, slot in slots:
            if not slot:
                continue
            name = slot.get("name", "Leisure / Rest")
            category = slot.get("category", "General")
            desc = slot.get("description", "")
            duration = slot.get("visit_duration", "2 hours")
            hours = slot.get("opening_hours", "09:00 - 18:00")
            fee_tot = slot.get("entry_fee_total", 0)
            food = slot.get("food_nearby", "")
            maps_url = slot.get("google_maps_url", "")

            details_html = f"<b>{name}</b> <font color='#2563EB'>({category})</font><br/>{desc}"
            if food:
                details_html += f"<br/><font color='#64748B'>🍲 <i>Nearby food:</i> {food}</font>"
            if maps_url and not slot.get("is_leisure", False):
                details_html += f"<br/><font color='#2563EB'><u><a href='{maps_url}'>📍 Open in Google Maps</a></u></font>"

            fee_str = "Free" if slot.get("is_leisure") else (f"{currency} {fee_tot:,.0f}" if fee_tot > 0 else "Free")

            day_rows.append([
                Paragraph(period_label, style_cell_bold),
                Paragraph(details_html, style_cell),
                Paragraph(f"<b>Duration:</b> {duration}<br/><b>Hours:</b> {hours}", style_cell),
                Paragraph(fee_str, style_cell_bold)
            ])

        # Interstitial travel info and meal break
        r_ma = d.get("route_morning_to_afternoon")
        r_ae = d.get("route_afternoon_to_evening")
        food_stop = d.get("suggested_food_stop", "")
        lunch_break = d.get("lunch_break", "")

        itin_day_table = Table(day_rows, colWidths=[usable_width * 0.22, usable_width * 0.46, usable_width * 0.18, usable_width * 0.14])
        itin_day_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), brand_dark),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ("GRID", (0, 0), (-1, -1), 0.5, border_color),
            ("PADDING", (0, 0), (-1, -1), 4),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        day_elements.append(itin_day_table)

        # Transit and lunch footnotes
        footer_notes = []
        if r_ma and r_ma.get("distance_km"):
            footer_notes.append(f"🚗 <b>Morning→Afternoon:</b> ~{r_ma.get('distance_km')} km ({r_ma.get('duration_formatted', '15 min')})")
        if food_stop:
            lunch_lbl = f"Lunch Break ({lunch_break}):" if lunch_break else "Lunch Stop:"
            footer_notes.append(f"🍲 <b>{lunch_lbl}</b> {food_stop}")
        if r_ae and r_ae.get("distance_km"):
            footer_notes.append(f"🚗 <b>Afternoon→Evening:</b> ~{r_ae.get('distance_km')} km ({r_ae.get('duration_formatted', '12 min')})")

        if footer_notes:
            day_elements.append(Spacer(1, 3))
            day_elements.append(Paragraph(" | ".join(footer_notes), style_body_muted))

        day_elements.append(Spacer(1, 8))
        elements.append(KeepTogether(day_elements))

    # ─── 7. GENERAL NOTES & DISCLAIMERS ───
    notes = trip_data.get("notes", [])
    if notes:
        elements.append(Spacer(1, 10))
        elements.append(Paragraph("📌 Travel Notes & Important Information", style_h1))
        for n in notes:
            elements.append(Paragraph(f"• {n}", style_body))

    # Build the document
    doc.build(elements, canvasmaker=NumberedCanvas)
    return buffer.getvalue()

